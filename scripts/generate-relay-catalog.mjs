// Inventory only: bid meanings remain in the profile definitions/source reviews.
// Run from any directory with: node scripts/generate-relay-catalog.mjs
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PRACTICE_PROFILES } from '../website/relay/profiles.js';
import { AUCTION_FAMILIES } from '../website/relay/families.js';
import { SYSTEM } from '../website/relay/system.js';
import { bidIndex } from '../website/relay/profile-utils.js';

const cell = value => String(value).replaceAll('|', '\\|').replace(/\r?\n/g, ' ');
const groups = Map.groupBy(PRACTICE_PROFILES, profile => profile.family);
const lines = [
  '# Exercise catalogue', '',
  '<!-- Generated by scripts/generate-relay-catalog.mjs. Edit profiles, then regenerate. -->', '',
  `The trainer offers **${AUCTION_FAMILIES.length} practice families** covering **${PRACTICE_PROFILES.length} study branches**.`,
  'Choose a family in the main toolbar to draw a random branch and hand.',
  'Open **Study a particular branch** to select one exact entry instead.', '',
  'Each row is a fixed auction entry. The next-call column lists the initial',
  'source actions; the app also offers applicable final contracts. Further',
  'asks depend on the answers and publicly established constraints.', '',
  'Every exercise supports asker or teller practice. The seat column records',
  'the source roles; choose which hand you play in the app toolbar.', '',
  'See the [system-table index](README.md) for meanings, [coverage](coverage.md)',
  'for exclusions, and the [maintenance guide](../relay-maintenance.md) for',
  'regeneration and verification.', '',
  '| Practice family | Branches |', '|---|---:|',
  ...AUCTION_FAMILIES.map(family => `| ${cell(family.name)} | ${family.profileIds.length} |`),
  `| **Total** | **${PRACTICE_PROFILES.length}** |`, '',
  'The source groups below retain their detailed bidding-system organization.',
  'The family picker separates 1D–1NT from the other minor three-bid entries',
  'and combines the reordered single-suiters, reverses and mini–mega splinters.', '',
];
for (const [family, profiles] of groups) {
  lines.push(`## ${family}`, '', '| Exercise / stable ID | Fixed auction prefix | Initial source calls | Asker / teller |', '|---|---|---|---|');
  for (const profile of profiles) {
    const major = profile.id.startsWith('major-');
    const prefix = major ? `1${profile.defaultTrump}` : profile.initialAuction.map(call => call.bid).join('–');
    const node = major ? null : profile.nodes[profile.startNode];
    if (!major && (!node || typeof node === 'function')) throw new Error(`Catalogue needs a static entry node: ${profile.id}`);
    const calls = major ? SYSTEM.raise : node.actions.map(action => action.bid).sort((left, right) => bidIndex(left) - bidIndex(right)).join(', ');
    lines.push(`| ${cell(profile.name)}<br>\`${profile.id}\` | ${cell(prefix)} | ${cell(calls)} | ${profile.playerSeat} / ${profile.partnerSeat} |`);
  }
  lines.push('');
}
const target = new URL('../docs/relay-system/scenario-catalog.md', import.meta.url);
fs.writeFileSync(target, lines.join('\n'));
console.log(`Documented ${PRACTICE_PROFILES.length} branches across ${AUCTION_FAMILIES.length} practice families in ${fileURLToPath(target)}`);
